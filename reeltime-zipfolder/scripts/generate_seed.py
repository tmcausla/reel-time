import json
import re
from pathlib import Path


SOURCE_FILE = Path("movieDb.js")
OUTPUT_FILE = Path("db/seed.sql")

GROUP_FIELD = "franchise"
ITEM_KEY_FIELDS = ("title", "releaseDate")

OBJECT_PATTERN = re.compile(r"\{([^{}]*)\}", re.DOTALL)

PROPERTY_PATTERN = re.compile(
    r'^\s*([A-Za-z_$][\w$]*)\s*:\s*'
    r'("(?:\\.|[^"\\])*"|\[[^\]]*\]|true|false|null|-?\d+(?:\.\d+)?)'
    r'\s*,?\s*$',
    re.MULTILINE
)


def parse_value(value):
    """Convert a supported JavaScript literal into a Python value."""
    if value.startswith('"') or value.startswith("["):
        return json.loads(value)

    if value == "true":
        return True

    if value == "false":
        return False

    if value == "null":
        return None

    if "." in value:
        return float(value)

    return int(value)


def parse_objects(source):
    """Extract supported object literals from the JavaScript file."""
    objects = []

    for match in OBJECT_PATTERN.finditer(source):
        body = match.group(1)
        properties = {}

        for prop_match in PROPERTY_PATTERN.finditer(body):
            name, value = prop_match.groups()
            properties[name] = parse_value(value)

        if not properties:
            continue

        required_fields = {
            "title",
            GROUP_FIELD,
            "director",
            "releaseDate",
        }

        missing_fields = required_fields - properties.keys()

        if missing_fields:
            raise ValueError(
                f"Object is missing fields: {', '.join(sorted(missing_fields))}"
            )

        if not isinstance(properties[GROUP_FIELD], list):
            raise ValueError(
                f"{GROUP_FIELD} must be an array in: {properties['title']}"
            )

        if not all(
            isinstance(name, str) for name in properties[GROUP_FIELD]
        ):
            raise ValueError(
                f"Every franchise must be a string in: {properties['title']}"
            )

        objects.append(properties)

    return objects


def sql_string(value):
    """Escape a Python string for use as an SQL string literal."""
    return "'" + value.replace("'", "''") + "'"


def sql_value(value):
    """Convert a Python value into an SQL literal."""
    if value is None:
        return "NULL"

    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"

    if isinstance(value, (int, float)):
        return str(value)

    return sql_string(value)


def generate_sql(objects):
    items = {}
    group_names = set()
    associations = set()

    for item in objects:
        item_key = tuple(item[field] for field in ITEM_KEY_FIELDS)
        items.setdefault(item_key, item)

        for group_name in item[GROUP_FIELD]:
            group_names.add(group_name)
            associations.add((item_key, group_name))

    lines = [
        "-- Generated by scripts/generate_seed.py",
        "-- Development seed data: this script replaces existing records.",
        "",
        "BEGIN;",
        "",
        "TRUNCATE TABLE movie_franchises, movies, franchises "
        "RESTART IDENTITY CASCADE;",
        "",
    ]

    for group_name in sorted(group_names):
        lines.append(
            "INSERT INTO franchises (name) VALUES "
            f"({sql_string(group_name)});"
        )

    lines.append("")

    for item_key, item in sorted(items.items()):
        title, release_date = item_key
        director = item["director"]

        lines.append(
            "INSERT INTO movies (title, director, release_date) VALUES "
            f"({sql_string(title)}, {sql_value(director)}, "
            f"{sql_string(release_date)});"
        )

    lines.append("")

    for item_key, group_name in sorted(associations):
        title, release_date = item_key

        lines.extend([
            "INSERT INTO movie_franchises (movie_id, franchise_id)",
            "SELECT m.id, f.id",
            "FROM movies AS m",
            "CROSS JOIN franchises AS f",
            f"WHERE m.title = {sql_string(title)}",
            f"  AND m.release_date = {sql_string(release_date)}",
            f"  AND f.name = {sql_string(group_name)};",
            "",
        ])

    lines.extend(["COMMIT;", ""])

    return "\n".join(lines)


def main():
    source = SOURCE_FILE.read_text(encoding="utf-8")
    objects = parse_objects(source)

    if not objects:
        raise ValueError(f"No objects found in {SOURCE_FILE}")

    sql = generate_sql(objects)

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(sql, encoding="utf-8")

    print(f"Generated seed SQL for {len(objects)} objects.")
    print(f"Output written to {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
